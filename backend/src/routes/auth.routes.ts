import { Router } from "express";
import { asyncHandler } from "../utils/asyncHandler";
import { register, login, me, forgotPassword, resetPassword, updateProfile, changePassword } from "../controllers/auth.controller";
import { requireAuth } from "../middleware/auth";
import { githubOAuthStart, googleOAuthStart, githubOAuthCallback, googleOAuthCallback, exchangeOAuthCode } from "../controllers/oauth.controller";
const router = Router();
router.post("/register", asyncHandler(register));
router.post("/login", asyncHandler(login));
router.get("/oauth/github", asyncHandler(githubOAuthStart));
router.get("/oauth/github/callback", asyncHandler(githubOAuthCallback));
router.get("/oauth/google", asyncHandler(googleOAuthStart));
router.get("/oauth/google/callback", asyncHandler(googleOAuthCallback));
router.post("/oauth/exchange", asyncHandler(exchangeOAuthCode));
router.get("/me", requireAuth, asyncHandler(me));
router.patch("/profile", requireAuth, asyncHandler(updateProfile));
router.post("/change-password", requireAuth, asyncHandler(changePassword));
router.post("/forgot-password", asyncHandler(forgotPassword));
router.post("/reset-password", asyncHandler(resetPassword));
export default router;
